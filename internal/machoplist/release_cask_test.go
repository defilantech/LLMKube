// The metal-agent cask (#822) is generated by GoReleaser from
// .goreleaser.yaml and published to the same tap as the CLI formula, which
// hack/publish-homebrew-formula.sh writes after GoReleaser runs. These tests
// pin the cask to the files it has to agree with: the build and archive it
// ships, the launchd plist it zaps, the CLI formula it names, and the
// release workflow that publishes both.

const (
	caskName        = "llmkube-metal-agent"
	caskBuildID     = "llmkube-metal-agent"
	cliFormula      = "defilantech/tap/llmkube"
	formulaScript   = "hack/publish-homebrew-formula.sh"
	releaseWorkflow = ".github/workflows/release-please.yml"
)

type goreleaserCask struct {
	Name        string   `json:"name"`
	IDs         []string `json:"ids"`
	Binaries    []string `json:"binaries"`
	Homepage    string   `json:"homepage"`
	Description string   `json:"description"`
	URL         struct {
		Template string `json:"template"`
	} `json:"url"`
	Dependencies []struct {
		Formula string `json:"formula"`
		Cask    string `json:"cask"`
	} `json:"dependencies"`
	Uninstall struct {
		Launchctl []string `json:"launchctl"`
	} `json:"uninstall"`
	Zap struct {
		Launchctl []string `json:"launchctl"`
		Trash     []string `json:"trash"`
	} `json:"zap"`
	Caveats      string `json:"caveats"`
	CommitAuthor struct {
		Name  string `json:"name"`
		Email string `json:"email"`
	} `json:"commit_author"`
	CommitMsgTemplate string `json:"commit_msg_template"`
	Directory         string `json:"directory"`
	SkipUpload        string `json:"skip_upload"`
	Repository        struct {
		Owner  string `json:"owner"`
		Name   string `json:"name"`
		Branch string `json:"branch"`
		Token  string `json:"token"`
	} `json:"repository"`
}

type goreleaserCaskConfig struct {
	Builds []struct {
		ID     string `json:"id"`
		Binary string `json:"binary"`
	} `json:"builds"`
	Archives []struct {
		ID  string   `json:"id"`
		IDs []string `json:"ids"`
	} `json:"archives"`
	HomebrewCasks []goreleaserCask `json:"homebrew_casks"`
	Release       struct {
		GitHub struct {
			Owner string `json:"owner"`
			Name  string `json:"name"`
		} `json:"github"`
	} `json:"release"`
}

func loadCaskConfig(t *testing.T) (goreleaserCaskConfig, goreleaserCask) {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(repoRoot, ".goreleaser.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	var cfg goreleaserCaskConfig
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		t.Fatalf("parse .goreleaser.yaml: %v", err)
	}
	var found []goreleaserCask
	for _, c := range cfg.HomebrewCasks {
		if c.Name == caskName {
			found = append(found, c)
		}
	}
	if len(found) != 1 {
		t.Fatalf("want exactly one homebrew_casks entry named %q, got %d", caskName, len(found))
	}
	return cfg, found[0]
}

// TestCaskShipsTheMetalAgentArchive checks the cask installs the metal-agent
// binary from the metal-agent archive and points at this repo's releases.
func TestCaskShipsTheMetalAgentArchive(t *testing.T) {
	cfg, cask := loadCaskConfig(t)

	var binary string
	for _, b := range cfg.Builds {
		if b.ID == caskBuildID {
			binary = b.Binary
		}
	}
	if binary == "" {
		t.Fatalf("no build %q in .goreleaser.yaml", caskBuildID)
	}
	if !slices.Equal(cask.Binaries, []string{binary}) {
		t.Errorf("cask binaries = %q, want [%q]", cask.Binaries, binary)
	}

	if len(cask.IDs) != 1 {
		t.Fatalf("cask ids = %q, want the one metal-agent archive id", cask.IDs)
	}
	var archiveBuilds []string
	for _, a := range cfg.Archives {
		if a.ID == cask.IDs[0] {
			archiveBuilds = a.IDs
		}
	}
	if !slices.Equal(archiveBuilds, []string{caskBuildID}) {
		t.Errorf("cask archive %q packs builds %q, want only [%q]", cask.IDs[0], archiveBuilds, caskBuildID)
	}

	gh := cfg.Release.GitHub
	wantURL := "https://github.com/" + gh.Owner + "/" + gh.Name + "/releases/download/{{ .Tag }}/{{ .ArtifactName }}"
	if cask.URL.Template != wantURL {
		t.Errorf("cask url template = %q, want %q (the release GoReleaser uploads to)", cask.URL.Template, wantURL)
	}
	if want := "https://github.com/" + gh.Owner + "/" + gh.Name; cask.Homepage != want {
		t.Errorf("cask homepage = %q, want %q", cask.Homepage, want)
	}
}

// TestCaskPassesBrewDescStyle mirrors the two rubocop Cask/Desc rules the
// generated cask is linted with, plus ASCII-only user-facing text.
func TestCaskPassesBrewDescStyle(t *testing.T) {
	_, cask := loadCaskConfig(t)

	if n := len(cask.Description); n == 0 || n >= 80 {
		t.Errorf("cask description is %d characters; brew style wants 1 to 79", n)
	}
	if strings.HasPrefix(strings.ToLower(cask.Description), "llmkube") {
		t.Errorf("cask description %q starts with the cask name; brew style rejects that", cask.Description)
	}
	for field, text := range map[string]string{"description": cask.Description, "caveats": cask.Caveats} {
		for _, r := range text {
			if r > unicode.MaxASCII {
				t.Errorf("cask %s has non-ASCII %q", field, r)
			}
		}
	}
	if !strings.Contains(cask.Caveats, "llmkube metal join") {
		t.Errorf("cask caveats do not say how to join a cluster: %q", cask.Caveats)
	}
}

// TestCaskPointsAtTheCLIFormula checks the cask depends on llama.cpp but not
// on the CLI formula, names the CLI formula in its caveats instead, that the
// release script publishes that formula to the cask's tap, and that no cask
// takes the token that script deletes.
//
// Not a dependency: since Homebrew 6.0, loading a formula from a tap the user
// has not trusted raises UntrustedTapError (Library/Homebrew/trust.rb
// require_trusted_formula!, called from formulary.rb load_formula), and
// `brew install <tap>/<cask>` trusts only the names on its command line
// (cmd/install.rb trust_fully_qualified_items!), so a fresh install of the
// cask would fail resolving the CLI dependency.
func TestCaskPointsAtTheCLIFormula(t *testing.T) {
	cfg, cask := loadCaskConfig(t)

	var formulae []string
	for _, d := range cask.Dependencies {
		if d.Formula != "" {
			formulae = append(formulae, d.Formula)
		}
	}
	if !slices.Contains(formulae, "llama.cpp") {
		t.Errorf("cask depends on formulae %q, want llama.cpp among them", formulae)
	}
	for _, f := range formulae {
		if strings.Count(f, "/") == 2 {
			t.Errorf("cask depends on %q from a third-party tap; Homebrew refuses it until the user runs brew trust", f)
		}
	}
	if !strings.Contains(cask.Caveats, "brew install "+cliFormula) {
		t.Errorf("cask caveats do not say to install the CLI with brew install %s: %q", cliFormula, cask.Caveats)
	}

	script, err := os.ReadFile(filepath.Join(repoRoot, formulaScript))
	if err != nil {
		t.Fatal(err)
	}
	formulaFile := "Formula/" + path.Base(cliFormula) + ".rb"
	if !strings.Contains(string(script), formulaFile) {
		t.Errorf("%s does not write %s, which the cask caveats name as %s", formulaScript, formulaFile, cliFormula)
	}
	tap := cask.Repository.Owner + "/" + strings.TrimPrefix(cask.Repository.Name, "homebrew-")
	if path.Dir(cliFormula) != tap {
		t.Errorf("cask publishes to tap %s but its caveats name %s from another tap", tap, cliFormula)
	}
	if !strings.Contains(string(script), `TAP_SLUG="`+cask.Repository.Owner+"/"+cask.Repository.Name+`"`) {
		t.Errorf("%s does not publish to %s/%s, the cask's tap", formulaScript, cask.Repository.Owner, cask.Repository.Name)
	}

	for _, c := range cfg.HomebrewCasks {
		if c.Name == path.Base(cliFormula) {
			t.Errorf("a cask named %q would be deleted by %s on every release", c.Name, formulaScript)
		}
	}
}

// TestCaskZapsTheLaunchAgent checks zap removes the job by the label the
// shipped launchd plist uses and clears the agent's log and state
// directories, and that uninstall does not touch the job.
//
// Not uninstall: Homebrew runs the old version's uninstall directives on
// `brew upgrade` as well, skipping only `signal`
// (Library/Homebrew/cask/artifact/abstract_uninstall.rb
// UPGRADE_REINSTALL_SKIP_DIRECTIVES; cask/installer.rb start_upgrade calls
// uninstall_artifacts), so `uninstall launchctl:` would delete the joined
// Mac's LaunchAgent on every upgrade.
func TestCaskZapsTheLaunchAgent(t *testing.T) {
	_, cask := loadCaskConfig(t)

	launchd := darwinReleaseBuilds[caskBuildID].launchd
	raw, err := os.ReadFile(filepath.Join(repoRoot, launchd))
	if err != nil {
		t.Fatal(err)
	}
	dict := parsePlistDict(t, raw)
	label, _ := dict["Label"].(string)
	if label == "" {
		t.Fatalf("%s has no Label", launchd)
	}
	if !slices.Equal(cask.Zap.Launchctl, []string{label}) {
		t.Errorf("cask zap launchctl = %q, want [%q] from %s", cask.Zap.Launchctl, label, launchd)
	}
	if len(cask.Uninstall.Launchctl) != 0 {
		t.Errorf("cask uninstall launchctl = %q; brew upgrade runs uninstall and would remove the joined LaunchAgent, use zap", cask.Uninstall.Launchctl)
	}
	if !strings.Contains(cask.Caveats, "launchctl kickstart -k gui/$(id -u)/"+label) {
		t.Errorf("cask caveats do not say how to restart %s after an upgrade: %q", label, cask.Caveats)
	}

	logPath, _ := dict["StandardOutPath"].(string)
	logDir := "~" + strings.TrimPrefix(path.Dir(logPath), "__HOME__")
	for _, want := range []string{logDir, "~/Library/Application Support/llmkube/metal-agent"} {
		if !slices.Contains(cask.Zap.Trash, want) {
			t.Errorf("cask zap trash = %q, want %q among them", cask.Zap.Trash, want)
		}
	}
	for _, p := range cask.Zap.Trash {
		if p == "~/Library/Application Support/llmkube" || strings.HasPrefix(p, "~/Library/Application Support/llmkube/models") {
			t.Errorf("cask zap trashes %q, which holds downloaded models shared beyond the agent", p)
		}
	}
}

// TestCaskPublishesBeforeTheCLIFormula checks the publishing side: the cask
// goes to the tap's main branch from the GoReleaser step (which has the tap
// token), skips snapshots and prereleases, and the formula script runs after
// it in the same job.
func TestCaskPublishesBeforeTheCLIFormula(t *testing.T) {
	_, cask := loadCaskConfig(t)

	if cask.Directory != "Casks" {
		t.Errorf("cask directory = %q, want Casks", cask.Directory)
	}
	if cask.SkipUpload != "auto" {
		t.Errorf("cask skip_upload = %q, want auto (no upload for snapshots and prereleases)", cask.SkipUpload)
	}
	r := cask.Repository
	if r.Owner != "defilantech" || r.Name != "homebrew-tap" || r.Branch != "main" {
		t.Errorf("cask repository = %s/%s@%s, want defilantech/homebrew-tap@main", r.Owner, r.Name, r.Branch)
	}
	if r.Token != "{{ .Env.HOMEBREW_TAP_TOKEN }}" {
		t.Errorf("cask repository token = %q, want {{ .Env.HOMEBREW_TAP_TOKEN }}", r.Token)
	}
	if !strings.Contains(cask.CommitMsgTemplate, caskName) {
		t.Errorf("cask commit message %q does not name the cask", cask.CommitMsgTemplate)
	}

	raw, err := os.ReadFile(filepath.Join(repoRoot, releaseWorkflow))
	if err != nil {
		t.Fatal(err)
	}
	var wf struct {
		Jobs map[string]struct {
			Steps []struct {
				Name string            `json:"name"`
				Run  string            `json:"run"`
				Uses string            `json:"uses"`
				Env  map[string]string `json:"env"`
			} `json:"steps"`
		} `json:"jobs"`
	}
	if err := yaml.Unmarshal(raw, &wf); err != nil {
		t.Fatalf("parse %s: %v", releaseWorkflow, err)
	}
	goreleaser, formula := -1, -1
	steps := wf.Jobs["goreleaser"].Steps
	for i, s := range steps {
		if strings.HasPrefix(s.Uses, "goreleaser/goreleaser-action@") {
			goreleaser = i
			if s.Env["HOMEBREW_TAP_TOKEN"] == "" {
				t.Errorf("%s: the GoReleaser step lacks HOMEBREW_TAP_TOKEN, so the cask cannot be pushed", releaseWorkflow)
			}
		}
		if strings.Contains(s.Run, formulaScript) {
			formula = i
		}
	}
	if goreleaser < 0 || formula < 0 {
		t.Fatalf("%s: goreleaser job has GoReleaser step %d and formula step %d; want both", releaseWorkflow, goreleaser, formula)
	}
	if formula < goreleaser {
		t.Errorf("%s: %s runs before GoReleaser publishes the cask; keep it after", releaseWorkflow, formulaScript)
	}
}
