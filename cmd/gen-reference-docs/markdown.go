// githubBlob is where a page links a source file. The site build rejects a
// relative link ending in .md, and a page rendered at /docs/reference/<slug>
// cannot reach repo files relatively anyway.
const githubBlob = "https://github.com/defilantech/LLMKube/blob/main/"

// pageHeader renders the frontmatter, the H1 and the "generated, do not edit"
// paragraph every reference page opens with. The frontmatter goes through the
// YAML encoder so a colon in a description is quoted rather than breaking it.
func pageHeader(title, description, sourceDesc string) string {
	fm, err := yaml.Marshal(struct {
		Title       string `yaml:"title"`
		Description string `yaml:"description"`
	}{title, description})
	if err != nil {
		// Two plain strings always encode; a failure here is a programming error.
		panic(err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "---\n%s---\n\n", fm)
	fmt.Fprintf(&b, "# %s\n\n", title)
	fmt.Fprintf(&b, "This page is generated by `make docs-reference` from %s. "+
		"Do not edit it by hand: change the source and regenerate.\n\n", sourceDesc)
	return b.String()
}

// sourceLink is a Markdown link to a repo file on GitHub, its path as the text.
func sourceLink(path string) string {
	return fmt.Sprintf("[`%s`](%s%s)", path, githubBlob, path)
}

// codeSpan wraps s in an inline code span whose fence is longer than any
// backtick run inside it, so source text that itself holds backticks cannot
// close the span early.
func codeSpan(s string) string {
	if s == "" {
		return ""
	}
	fence := strings.Repeat("`", longestRun(s, '`')+1)
	if strings.HasPrefix(s, "`") || strings.HasSuffix(s, "`") {
		return fence + " " + s + " " + fence
	}
	return fence + s + fence
}

// codeBlock renders s as a fenced block. The fence outgrows any backtick run
// in s for the same reason codeSpan's does.
func codeBlock(lang, s string) string {
	n := max(longestRun(s, '`')+1, 3)
	fence := strings.Repeat("`", n)
	return fence + lang + "\n" + strings.TrimRight(s, "\n") + "\n" + fence + "\n\n"
}

func longestRun(s string, r rune) int {
	best, cur := 0, 0
	for _, c := range s {
		if c == r {
			cur++
			best = max(best, cur)
		} else {
			cur = 0
		}
	}
	return best
}

// tableCell turns free text into one Markdown table cell: whitespace and
// newlines collapse to single spaces (a raw newline ends the row) and every
// pipe is escaped, including those inside code spans, which GFM splits on too.
func tableCell(s string) string {
	return strings.ReplaceAll(inlineText(collapseSpace(s)), "|", `\|`)
}

// tableRow joins already-rendered cells into one table row.
func tableRow(cells ...string) string {
	return "| " + strings.Join(cells, " | ") + " |\n"
}

// tableHeader renders a header row and its delimiter row.
func tableHeader(cols ...string) string {
	delims := make([]string, len(cols))
	for i := range cols {
		delims[i] = "---"
	}
	return tableRow(cols...) + tableRow(delims...)
}

func collapseSpace(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// inlineText escapes free text (a help string, a YAML comment, a CRD
// description) for use as Markdown prose, leaving the author's code spans
// intact.
//
// The site compiles Markdown with mdsvex into Svelte, which constrains prose
// beyond CommonMark. A brace in prose opens a Svelte expression, and mdsvex
// decodes every entity for one (&#123;, \{) back into a bare brace before
// Svelte sees it; only inside code does mdsvex escape braces itself. So a
// token holding a brace becomes inline code, which reads right anyway: it is
// JSON, a template or a set. mdsvex's smartypants pass also turns "--" in
// prose into a dash, which would print --max-watch-failures as an em dash and
// a word; a --flag token becomes inline code for the same reason. An angle
// bracket would open an element, so it becomes an entity, which mdsvex keeps.
// Markdown's own syntax characters are backslash-escaped so a stray asterisk
// or bracket cannot turn into emphasis or a link.
func inlineText(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); {
		j := i
		for j < len(s) && s[j] != '`' {
			j++
		}
		b.WriteString(escapeProse(s[i:j]))
		if j == len(s) {
			break
		}
		n := backtickRun(s, j)
		if end, ok := codeSpanEnd(s, j, n); ok {
			b.WriteString(s[j:end])
			i = end
			continue
		}
		// An unmatched backtick run is literal text in CommonMark; escaping it
		// keeps it literal even if later text would otherwise pair with it.
		b.WriteString(strings.Repeat("\\`", n))
		i = j + n
	}
	return b.String()
}

// escapeProse escapes text that holds no code span.
func escapeProse(s string) string {
	var b strings.Builder
	last := 0
	for _, r := range codeRanges(s) {
		b.WriteString(escapeChars(s[last:r[0]]))
		b.WriteString(codeSpan(s[r[0]:r[1]]))
		last = r[1]
	}
	b.WriteString(escapeChars(s[last:]))
	return b.String()
}

// codeRanges finds the substrings escapeProse renders as inline code: a brace
// group (to its matching brace, or the brace alone when unmatched) widened to
// the whitespace-delimited token around it, a --flag token, and a bare URL.
// Ranges come back ordered and disjoint.
func codeRanges(s string) [][2]int {
	var out [][2]int
	for i := 0; i < len(s); {
		var start, end int
		switch {
		case s[i] == '{' || s[i] == '}':
			end = i + 1
			if s[i] == '{' {
				end = matchBrace(s, i)
			}
			start, end = widenToken(s, i, end)
		case isFlagStart(s, i):
			start, end = widenToken(s, i, i+2)
		case isURLStart(s, i):
			start, end = widenToken(s, i, i+1)
		default:
			i++
			continue
		}
		if n := len(out); n > 0 && start <= out[n-1][1] {
			out[n-1][1] = max(out[n-1][1], end)
		} else {
			out = append(out, [2]int{start, end})
		}
		i = end
	}
	return out
}

// matchBrace returns the index just past the brace closing the one at i, or
// i+1 when it is never closed.
func matchBrace(s string, i int) int {
	depth := 0
	for j := i; j < len(s); j++ {
		switch s[j] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return j + 1
			}
		}
	}
	return i + 1
}

// isFlagStart reports a "--" that begins a token and is followed by a letter,
// as in --max-watch-failures; "a -- b" is prose and is left alone.
func isFlagStart(s string, i int) bool {
	return strings.HasPrefix(s[i:], "--") && i+2 < len(s) && isAlnum(s[i+2]) &&
		(i == 0 || s[i-1] == ' ' || s[i-1] == '(' || s[i-1] == '"' || s[i-1] == '\'')
}

// isURLStart reports an http(s) URL that begins a token. GFM turns a bare URL
// into a link, and the descriptions these pages quote hold URLs that make
// invalid links: a placeholder (http://llmkube.<namespace>.svc...) or a
// closing quote GFM keeps in the link ("http://host:4000"). The site's
// prerender rejects an invalid link and fails the whole build, so every bare
// URL becomes inline code; they are in-cluster examples, not pages to visit.
func isURLStart(s string, i int) bool {
	return (strings.HasPrefix(s[i:], "http://") || strings.HasPrefix(s[i:], "https://")) &&
		(i == 0 || isSpace(s[i-1]) || strings.ContainsRune(`("'`, rune(s[i-1])))
}

// widenToken extends [start, end) to the surrounding token, leaving off
// opening punctuation before it and closing punctuation after it, so
// "(see {a}.)" wraps only "{a}".
func widenToken(s string, start, end int) (int, int) {
	for start > 0 && !isSpace(s[start-1]) && !strings.ContainsRune(`("'[`, rune(s[start-1])) {
		start--
	}
	for end < len(s) && !isSpace(s[end]) {
		end++
	}
	for end > start+1 && strings.ContainsRune(`.,;:!?)"']`, rune(s[end-1])) && s[end-1] != '}' {
		end--
	}
	return start, end
}

func isSpace(c byte) bool {
	return c == ' ' || c == '\t' || c == '\n'
}

// escapeChars escapes prose character by character. Every byte it rewrites is
// ASCII, so walking bytes leaves multi-byte UTF-8 sequences untouched.
func escapeChars(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		if esc, ok := proseEscapes[s[i]]; ok && !intrawordUnderscore(s, i) {
			b.WriteString(esc)
		} else {
			b.WriteByte(s[i])
		}
	}
	return b.String()
}

var proseEscapes = map[byte]string{
	'&':  "&amp;",
	'<':  "&lt;",
	'>':  "&gt;",
	'\\': `\\`,
	'*':  `\*`,
	'_':  `\_`,
	'[':  `\[`,
	']':  `\]`,
}

// intrawordUnderscore reports an underscore between two alphanumerics, as in
// a metric or variable name. CommonMark never reads one as emphasis, so it
// stays unescaped and the source of the page stays readable.
func intrawordUnderscore(s string, i int) bool {
	return s[i] == '_' && i > 0 && i+1 < len(s) && isAlnum(s[i-1]) && isAlnum(s[i+1])
}

func isAlnum(c byte) bool {
	return c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
}

func backtickRun(s string, i int) int {
	n := 0
	for i+n < len(s) && s[i+n] == '`' {
		n++
	}
	return n
}

// codeSpanEnd reports where the code span opened by the n-backtick run at
// start ends: just past a closing run of exactly the same length.
func codeSpanEnd(s string, start, n int) (int, bool) {
	for j := start + n; j < len(s); {
		if s[j] != '`' {
			j++
			continue
		}
		m := backtickRun(s, j)
		if m == n {
			return j + m, true
		}
		j += m
	}
	return 0, false
}

// anchor is the GitHub-style heading slug: lower case, spaces to hyphens,
// punctuation other than hyphen and underscore dropped.
func anchor(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r == ' ':
			b.WriteByte('-')
		case r == '-' || r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r):
			b.WriteRune(r)
		}
	}
	return b.String()
}

// dedent removes the indentation every non-blank line of s shares, so an
// Example written with the conventional two-space indent renders flush.
func dedent(s string) string {
	lines := strings.Split(strings.Trim(s, "\n"), "\n")
	common := -1
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			continue
		}
		n := len(l) - len(strings.TrimLeft(l, " \t"))
		if common < 0 || n < common {
			common = n
		}
	}
	for i, l := range lines {
		if common > 0 && len(l) >= common {
			lines[i] = l[common:]
		}
		lines[i] = strings.TrimRight(lines[i], " \t")
	}
	return strings.Join(lines, "\n")
}
