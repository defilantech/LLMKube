// A page that fails to render must not leave the others half-updated.
func TestRunWritesNothingWhenAPageFails(t *testing.T) {
	out := filepath.Join(t.TempDir(), "reference")
	if err := run(t.TempDir(), out); err == nil {
		t.Fatal("run over a root with no charts or CRDs succeeded")
	}
	if _, err := os.Stat(out); !os.IsNotExist(err) {
		t.Errorf("run wrote %s despite failing: %v", out, err)
	}
}

// relativeMDLink is the site build's rejection rule: a relative link whose
// target ends in .md.
var relativeMDLink = regexp.MustCompile(`\]\(\.{0,2}/?[^)h#][^)]*\.md(#[^)]*)?\)`)

// rawTag is what a Svelte compile of the page would read as an element.
var rawTag = regexp.MustCompile(`<[A-Za-z/!]`)

func TestGeneratedPagesAreSiteSafe(t *testing.T) {
	dir := t.TempDir()
	if err := run("../..", dir); err != nil {
		t.Fatal(err)
	}
	for _, p := range pages {
		data, err := os.ReadFile(filepath.Join(dir, p.file))
		if err != nil {
			t.Fatal(err)
		}
		page := string(data)
		checkFrontmatter(t, p.file, page)
		if m := relativeMDLink.FindString(page); m != "" {
			t.Errorf("%s: relative .md link %q", p.file, m)
		}
		checkProse(t, p.file, page)
	}
}

func checkFrontmatter(t *testing.T, file, page string) {
	t.Helper()
	parts := strings.SplitN(page, "---\n", 3)
	if len(parts) != 3 || parts[0] != "" {
		t.Fatalf("%s: no frontmatter", file)
	}
	var fm struct {
		Title       string `yaml:"title"`
		Description string `yaml:"description"`
	}
	if err := yaml.Unmarshal([]byte(parts[1]), &fm); err != nil || fm.Title == "" || fm.Description == "" {
		t.Errorf("%s: frontmatter %q: %v", file, parts[1], err)
	}
	if !strings.HasPrefix(parts[2], "\n# "+fm.Title+"\n\nThis page is generated by `make docs-reference`") {
		t.Errorf("%s: does not open with the H1 and the generated-by paragraph", file)
	}
}

// checkProse walks the page outside fenced blocks: every table row has its
// header's cell count (an unescaped pipe or a newline in a cell breaks that),
// and no brace or tag survives outside inline code.
func checkProse(t *testing.T, file, page string) {
	t.Helper()
	fence := ""
	cols := 0
	for n, line := range strings.Split(page, "\n") {
		if fence != "" {
			if strings.HasPrefix(line, fence) && strings.Trim(line, "`") == "" {
				fence = ""
			}
			continue
		}
		if strings.HasPrefix(line, "```") {
			fence = line[:len(line)-len(strings.TrimLeft(line, "`"))]
			continue
		}
		if strings.HasPrefix(line, "|") {
			cells := len(splitRow(line))
			if cols == 0 {
				cols = cells
			} else if cells != cols {
				t.Errorf("%s:%d: %d cells, header has %d: %s", file, n+1, cells, cols, line)
			}
		} else {
			cols = 0
		}
		prose := stripCodeSpans(line)
		if strings.ContainsAny(prose, "{}") || rawTag.MatchString(prose) {
			t.Errorf("%s:%d: brace or tag outside code: %s", file, n+1, line)
		}
	}
}

func splitRow(line string) []string {
	var cells []string
	cur := strings.Builder{}
	for i := 0; i < len(line); i++ {
		switch {
		case line[i] == '\\' && i+1 < len(line):
			cur.WriteByte(line[i])
			cur.WriteByte(line[i+1])
			i++
		case line[i] == '|':
			cells = append(cells, cur.String())
			cur.Reset()
		default:
			cur.WriteByte(line[i])
		}
	}
	// The leading and trailing pipes delimit nothing.
	return cells[1:]
}

// stripCodeSpans drops inline code: a backtick run up to the next run of the
// same length. Written independently of the renderer's own scanner.
func stripCodeSpans(line string) string {
	var out strings.Builder
	for i := 0; i < len(line); {
		if line[i] == '\\' && i+1 < len(line) {
			out.WriteString(line[i : i+2])
			i += 2
			continue
		}
		if line[i] != '`' {
			out.WriteByte(line[i])
			i++
			continue
		}
		run := len(line[i:]) - len(strings.TrimLeft(line[i:], "`"))
		fenceStr := line[i : i+run]
		rest := line[i+run:]
		closeAt := -1
		for j := 0; j+run <= len(rest); j++ {
			if rest[j:j+run] == fenceStr && (j+run == len(rest) || rest[j+run] != '`') && (j == 0 || rest[j-1] != '`') {
				closeAt = j
				break
			}
		}
		if closeAt < 0 {
			out.WriteString(fenceStr)
			i += run
			continue
		}
		i += run + closeAt + run
	}
	return out.String()
}
